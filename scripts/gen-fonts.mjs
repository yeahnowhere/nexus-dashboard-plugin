// Generate FIGlet font modules from the canonical patorjk/figlet.js fonts.
//
// Usage:
//   node scripts/gen-fonts.mjs "Slant" "Small Slant" "Standard" "Graffiti"
//   npm run gen:fonts -- "Big" "Doom"
//
// With no arguments it regenerates the fonts currently registered by the plugin.
// The upstream `.flf` files are MIT licensed; each generated module carries the
// original font's notice from its comment block.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FONTS_DIR = resolve(root, "src/fonts");
const BASE_URL = "https://raw.githubusercontent.com/patorjk/figlet.js/main/fonts";

/** Fonts to (re)generate when run without arguments. */
const DEFAULT_FONTS = ["Slant", "Small Slant", "Standard", "Graffiti"];

/** Turn a font name into the module filename slug ("Small Slant" → "small-slant"). */
function slugify(name) {
	return name
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, "-")
		.replace(/^-+|-+$/g, "");
}

/**
 * Parse a FIGlet `.flf` string into a font definition.
 *
 * @param {string} text - Raw `.flf` file contents.
 * @returns {{height: number, hardblank: string, notice: string[], chars: Record<string, string[]>}}
 */
function parseFlf(text) {
	const lines = text.split(/\r?\n/);
	const header = lines[0];
	if (!header.startsWith("flf2a")) {
		throw new Error(`Not a FIGlet font (header: ${JSON.stringify(header)})`);
	}

	const hardblank = header[5];
	const fields = header.split(/\s+/);
	const height = Number.parseInt(fields[1], 10);
	const commentLines = Number.parseInt(fields[5], 10) || 0;
	if (!Number.isFinite(height) || height <= 0) {
		throw new Error(`Invalid height in header: ${JSON.stringify(header)}`);
	}

	const notice = lines.slice(1, 1 + commentLines).map((l) => l.trimEnd());
	let idx = 1 + commentLines;

	const chars = {};
	for (let code = 32; code <= 126; code++) {
		const glyph = [];
		for (let row = 0; row < height; row++) {
			glyph.push(lines[idx++] ?? "");
		}
		const endmark = glyph[0].slice(-1);
		const cleaned = glyph.map((line, row) => {
			let s = line;
			if (s.endsWith(endmark)) s = s.slice(0, -1);
			if (row === height - 1 && s.endsWith(endmark)) s = s.slice(0, -1);
			return endmark ? s.split(hardblank).join(" ") : s;
		});
		chars[String.fromCharCode(code)] = cleaned;
	}

	return { height, hardblank, notice, chars };
}

/**
 * Render a parsed font as a TypeScript module matching the repo's font shape.
 *
 * @param {string} name - Canonical font name.
 * @param {number} height - Glyph height.
 * @param {string[]} notice - Original `.flf` comment block.
 * @param {Record<string, string[]>} chars - Parsed glyph map.
 * @returns {string}
 */
function renderModule(name, height, notice, chars) {
	const file = `${name}.flf`;
	const header = [
		`// ${name} FIGlet font — generated by scripts/gen-fonts.mjs`,
		`// Source: https://github.com/patorjk/figlet.js/blob/main/fonts/${encodeURIComponent(file)} (MIT)`,
		"// Original font notice:",
		...notice.map((line) => `// ${line}`.trimEnd()),
		"",
	];

	const body = [
		`export type FigletChar = string[]; // array of ${height} strings (lines)`,
		"",
		`export const FONT_NAME = ${JSON.stringify(name)};`,
		`export const FONT_HEIGHT = ${height};`,
		"",
		"// prettier-ignore",
		"export const CHARS: Record<string, FigletChar> = {",
	];

	for (const [key, glyph] of Object.entries(chars)) {
		body.push(`\t${JSON.stringify(key)}: [`);
		for (const line of glyph) {
			body.push(`\t\t${JSON.stringify(line)},`);
		}
		body.push("\t],");
	}
	body.push("};", "");

	return header.concat(body).join("\n");
}

async function fetchFont(name) {
	const url = `${BASE_URL}/${encodeURIComponent(`${name}.flf`)}`;
	const res = await fetch(url);
	if (!res.ok) {
		throw new Error(`Failed to download ${name}.flf (HTTP ${res.status})`);
	}
	return res.text();
}

async function generate(name) {
	const slug = slugify(name);
	const raw = await fetchFont(name);
	const { height, notice, chars } = parseFlf(raw);
	const out = resolve(FONTS_DIR, `${slug}.ts`);
	writeFileSync(out, renderModule(name, height, notice, chars), "utf8");
	console.log(`[gen-fonts] ${name} → src/fonts/${slug}.ts (height ${height})`);
}

const names = process.argv.slice(2);
const targets = names.length > 0 ? names : DEFAULT_FONTS;

for (const name of targets) {
	await generate(name);
}
console.log(`[gen-fonts] Done (${targets.length} font${targets.length === 1 ? "" : "s"}).`);
